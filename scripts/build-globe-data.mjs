// Builds src/data/brazilStates.js from IBGE's official state mesh (API de Malhas
// Geográficas v3, "qualidade=minima"). Run with: node scripts/build-globe-data.mjs
//
// Output: for each of the 27 UFs, its outer rings as flat [lon, lat, lon, lat, ...]
// arrays rounded to 0.01° (~1 km) and simplified (Douglas–Peucker, 0.02°), which
// is far below a pixel even at the globe's closest zoom.

import { writeFileSync } from 'node:fs';

const SOURCE =
  'https://servicodados.ibge.gov.br/api/v3/malhas/paises/BR?formato=application/vnd.geo+json&qualidade=minima&intrarregiao=UF';

const UF = {
  11: ['RO', 'Rondônia'], 12: ['AC', 'Acre'], 13: ['AM', 'Amazonas'], 14: ['RR', 'Roraima'],
  15: ['PA', 'Pará'], 16: ['AP', 'Amapá'], 17: ['TO', 'Tocantins'], 21: ['MA', 'Maranhão'],
  22: ['PI', 'Piauí'], 23: ['CE', 'Ceará'], 24: ['RN', 'Rio Grande do Norte'], 25: ['PB', 'Paraíba'],
  26: ['PE', 'Pernambuco'], 27: ['AL', 'Alagoas'], 28: ['SE', 'Sergipe'], 29: ['BA', 'Bahia'],
  31: ['MG', 'Minas Gerais'], 32: ['ES', 'Espírito Santo'], 33: ['RJ', 'Rio de Janeiro'], 35: ['SP', 'São Paulo'],
  41: ['PR', 'Paraná'], 42: ['SC', 'Santa Catarina'], 43: ['RS', 'Rio Grande do Sul'], 50: ['MS', 'Mato Grosso do Sul'],
  51: ['MT', 'Mato Grosso'], 52: ['GO', 'Goiás'], 53: ['DF', 'Distrito Federal'],
};

const TOLERANCE = 0.02;

function simplify(points, tolerance = TOLERANCE) {
  if (points.length < 4) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = points[a];
    const [bx, by] = points[b];
    const dx = bx - ax;
    const dy = by - ay;
    const len = Math.hypot(dx, dy);
    let worst = -1;
    let index = -1;
    for (let i = a + 1; i < b; i++) {
      // Closed rings start and end on the same point: fall back to plain distance.
      const d = len
        ? Math.abs(dy * points[i][0] - dx * points[i][1] + bx * ay - by * ax) / len
        : Math.hypot(points[i][0] - ax, points[i][1] - ay);
      if (d > worst) {
        worst = d;
        index = i;
      }
    }
    if (worst > tolerance) {
      keep[index] = 1;
      stack.push([a, index], [index, b]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

const round = (n) => Math.round(n * 100) / 100;

const geo = await (await fetch(SOURCE)).json();
const states = geo.features
  .map((feature) => {
    const [uf, name] = UF[feature.properties.codarea];
    const polygons = feature.geometry.type === 'Polygon' ? [feature.geometry.coordinates] : feature.geometry.coordinates;
    const rings = polygons
      .map((polygon) => simplify(polygon[0].map(([lon, lat]) => [round(lon), round(lat)])))
      .filter((ring) => ring.length >= 4)
      .map((ring) => ring.flat());
    return { uf, name, rings };
  })
  .sort((a, b) => a.uf.localeCompare(b.uf));

const body = states.map((s) => `  ${JSON.stringify(s)},`).join('\n');
writeFileSync(
  new URL('../src/data/brazilStates.js', import.meta.url),
  `// Generated by scripts/build-globe-data.mjs from IBGE (API de Malhas Geográficas v3).
// Outer rings of each UF as flat [lon, lat, ...] arrays, simplified to ~2 km.
export const BRAZIL_STATES = [
${body}
];
`,
);
console.log(`wrote ${states.length} states, ${states.reduce((n, s) => n + s.rings.reduce((m, r) => m + r.length / 2, 0), 0)} points`);

// ---------- The three LWN office cities (municipality outlines) ----------
// Drawn when the globe zooms to city level in "Onde encontrar o Grupo LWN".
// Finer mesh ("intermediaria"), rounded to 0.001° and simplified to ~0.2 km.

const CITIES = [
  { id: 'saoPaulo', code: 3550308 },
  { id: 'barueri', code: 3505708 },
  { id: 'anapolis', code: 5201108 },
];
const fine = (n) => Math.round(n * 1000) / 1000;

const cities = [];
for (const { id, code } of CITIES) {
  const url = `https://servicodados.ibge.gov.br/api/v3/malhas/municipios/${code}?formato=application/vnd.geo+json&qualidade=intermediaria`;
  const feature = (await (await fetch(url)).json()).features[0];
  const polygons = feature.geometry.type === 'Polygon' ? [feature.geometry.coordinates] : feature.geometry.coordinates;
  const rings = polygons
    .map((polygon) => simplify(polygon[0].map(([lon, lat]) => [fine(lon), fine(lat)]), 0.002))
    .filter((ring) => ring.length >= 4)
    .map((ring) => ring.flat());
  cities.push({ id, rings });
}

writeFileSync(
  new URL('../src/data/cityShapes.js', import.meta.url),
  `// Generated by scripts/build-globe-data.mjs from IBGE (API de Malhas Geográficas v3).
// Municipality outlines of the LWN office cities, keyed by office id.
export const CITY_SHAPES = {
${cities.map((c) => `  ${c.id}: ${JSON.stringify(c.rings)},`).join('\n')}
};
`,
);
console.log(`wrote ${cities.length} cities, ${cities.reduce((n, c) => n + c.rings.reduce((m, r) => m + r.length / 2, 0), 0)} points`);
